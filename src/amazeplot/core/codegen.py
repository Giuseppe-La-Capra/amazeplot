"""Turn a :class:`DataSession` into a standalone Python script.

The script is the "receipt" of a GUI session: running it reproduces the
current DataFrame without the GUI, which makes every analysis auditable
and teaches users the pandas API behind each button.
"""

from __future__ import annotations

from amazeplot.core.session import DataSession

_HEADER = '"""Data pipeline generated by amazeplot."""'
_PLACEHOLDER_SOURCE = "{variable} = pd.DataFrame()  # TODO: load your data"


def generate_script(session: DataSession, variable: str = "df") -> str:
    """Return a runnable script that replays every step of ``session``.

    Parameters
    ----------
    session : DataSession
        The session to export.
    variable : str, default "df"
        Name of the DataFrame variable used in the script.

    Returns
    -------
    str
        PEP 8 formatted Python source ending with a newline.
    """
    if not variable.isidentifier():
        raise ValueError(f"Invalid variable name: {variable!r}")
    source = session.source
    load = (
        source.to_code(variable)
        if source is not None
        else _PLACEHOLDER_SOURCE.format(variable=variable)
    )
    lines = [_HEADER, "", "import pandas as pd", "", load]
    lines += [step.to_code(variable) for step in session.steps]
    return "\n".join(lines) + "\n"
