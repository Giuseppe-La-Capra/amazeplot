"""Turn a :class:`DataSession` into a standalone Python script.

The script is the "receipt" of a GUI session: running it reproduces the
current DataFrame and figure without the GUI. This makes every analysis
auditable and teaches users the pandas and matplotlib APIs behind each
button.
"""

from __future__ import annotations

from amazeplot.core.plotting import AXES_VARIABLE
from amazeplot.core.session import DataSession

_HEADER = '"""Data pipeline generated by amazeplot."""'
_PLACEHOLDER_SOURCE = "{variable} = pd.DataFrame()  # TODO: load your data"
_PYPLOT_IMPORT = "import matplotlib.pyplot as plt"
_PANDAS_IMPORT = "import pandas as pd"
_CREATE_FIGURE = f"fig, {AXES_VARIABLE} = plt.subplots()"
_SHOW_FIGURE = "plt.show()"


def generate_script(session: DataSession, variable: str = "df") -> str:
    """Return a runnable script that replays every step of ``session``.

    Parameters
    ----------
    session : DataSession
        The session to export.
    variable : str, default "df"
        Name of the DataFrame variable used in the script.

    Returns
    -------
    str
        PEP 8 formatted Python source ending with a newline. The
        matplotlib part is only included when the session has plot
        layers, and other imports (such as numpy) only when a step
        needs them.
    """
    if not variable.isidentifier():
        raise ValueError(f"Invalid variable name: {variable!r}")
    has_plot = bool(session.layers)
    source = session.source
    load = (
        source.to_code(variable)
        if source is not None
        else _PLACEHOLDER_SOURCE.format(variable=variable)
    )

    imports = {_PANDAS_IMPORT}
    if has_plot:
        imports.add(_PYPLOT_IMPORT)
    for action in [step.operation for step in session.steps] + [
        layer.call for layer in session.layers
    ]:
        imports.update(action.code_imports)
    lines = [_HEADER, "", *sorted(imports), "", load]
    lines += [step.to_code(variable) for step in session.steps]
    if has_plot:
        lines += ["", _CREATE_FIGURE]
        lines += [layer.to_code(variable) for layer in session.layers]
        lines.append(_SHOW_FIGURE)
    return "\n".join(lines) + "\n"
